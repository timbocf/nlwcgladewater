        <h2>Note from our Senior Pastors:</h2>
        <p>"Let us first say thank you for taking your valuable time and using it to visit our website. New Life Worship Center is a contemporary Spirit-filled church. Our vision and mission here is to advance the Kingdom one soul at a time through the ministry of Jesus Christ. We believe the people of this East Texas area need a spiritual place to come and encounter God without being judged, condemned, and shunned.</p>
        <p>Without doubt, God has raised up such a place in the midst of this body of believers. Regardless of your age, gender, or race, we personally invite you to come and experience for yourself the wonderful love, peace, and healing power of God that is flowing out upon the people in each and every service.</p>
        <p>So what are you waiting for? Load up all your worries, problems, and pain that you don't need anymore and come give them to Jesus! We pray that you have a wonderfully blessed day, and remember... regardless of what your surroundings are saying to you, God really does care, and He loves you very much!"</p>
        <h3>- Senior Pastors <br />
            Steve and Rose Goude</h3>
